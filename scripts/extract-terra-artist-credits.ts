import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

type Operator = { id: string; name: string };
type ApiResponse = { parse?: { pageid: number; wikitext?: string | { "*": string } }; error?: { code?: string; info?: string } };
type RevisionResponse = { query?: { pages?: Array<{ revisions?: Array<{ revid: number; timestamp: string }> }> }; error?: { code?: string; info?: string } };
type CompactRecord = { operatorId: string; operatorName: string; terraPage?: string | null; pageId?: number | null; source: Record<string, unknown>; sourceFields?: { illustrator?: string | null }; extractedArtists: { name: string; role?: string; evidence: string }[]; derivedCredits: unknown[]; variants: Record<string, unknown[]>; status: "verified" | "partial" | "pending"; error?: unknown; warnings?: unknown; lastRefreshError?: unknown };

